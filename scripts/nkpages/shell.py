def secbar(D, R):
    links = []
    for key, path, label, cls, aria in BAR:
        a = [f'href="{rel(R, path)}"', f'data-nav="{key}"']
        if cls:
            a.append(f'class="{cls}"')
        if aria:
            a.append(f'aria-label="{aria}"')
        if R.nav == key:
            a.append('aria-current="page"')
        links.append(f'<a {" ".join(a)}>{label}</a>')
    return ('<nav class="secbar" aria-label="Sections"><div class="page"><div class="links">' + "".join(links) +
            '</div>' + more(D, R) +
            '<button type="button" class="theme-btn w720" data-theme-toggle>Dark</button></div></nav>')


