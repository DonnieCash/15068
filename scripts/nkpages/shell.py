def crumbs_html(R, crumbs):
    """Visible breadcrumbs only when there is a parent to go back to; a lone crumb would read as a label over the
    H1 (the JSON-LD BreadcrumbList still carries it)."""
    if not crumbs or not any(path for _, path in crumbs):
        return ""
    parts = []
    for label, path in crumbs:
        parts.append(f'<a href="{rel(R, path)}">{esc(label)}</a>' if path else f'<span aria-current="page">{esc(label)}</span>')
    return '<nav class="crumbs page" aria-label="Breadcrumb">' + " › ".join(parts) + "</nav>"


# --------------------------------------------------------------------------- ads


def head_ads(D, R):
    if not ads_on(D) or R.ads != "C":
        return ""
    c = esc(D["cfg"]["adsense_client"].strip())
    return (f'<script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client={c}" '
            'crossorigin="anonymous"></script>')


def ad_slot(D, R, which):
    slot = ((D["cfg"].get("adsense_slots") or {}).get(which) or "").strip()
    if not ads_on(D) or R.ads != "C" or not slot:
        return ""
    c = esc(D["cfg"]["adsense_client"].strip())
    return ('<aside class="adslot" aria-label="Advertisement"><p class="adslot-label">Advertisement</p>'
            f'<ins class="adsbygoogle" style="display:block" data-ad-client="{c}" data-ad-slot="{esc(slot)}" '
            'data-ad-format="auto" data-full-width-responsive="true"></ins>'
            '<script>(adsbygoogle = window.adsbygoogle || []).push({});</script></aside>')


def place_ads(D, R, main):
    """Replace <!--AD:mid|end--> markers: a slot only when configured, on a C route, after >= 250 words of main text
    and after every data-keep-above element; otherwise nothing."""
    out, pos = [], 0
    for m in AD_MARK.finditer(main):
        out.append(main[pos:m.start()])
        before, after = main[:m.start()], main[m.end():]
        ok = fmt.words(before) >= AD_MIN_WORDS and "data-keep-above" not in after
        out.append(ad_slot(D, R, m.group(1)) if ok else "")
        pos = m.end()
    out.append(main[pos:])
    return "".join(out)


# --------------------------------------------------------------------------- JSON-LD


def jsonld_tag(obj):
    return f'<script type="application/ld+json">{fmt.json_script(obj)}</script>'


def site_url(D):
    return D["cfg"]["site_url"].rstrip("/")


def jsonld_website(D):
    u = site_url(D)
    return {"@context": "https://schema.org", "@type": "WebSite", "name": "NK15068", "url": u + "/",
            "potentialAction": {"@type": "SearchAction", "target": u + "/search/?q={search_term_string}",
                                "query-input": "required name=search_term_string"}}


def jsonld_breadcrumbs(D, R, crumbs):
    u = site_url(D)
    items = [("NK15068", "/")] + [(l, p or R.path) for l, p in (crumbs or [(short_title(R), None)])]
    return {"@context": "https://schema.org", "@type": "BreadcrumbList",
            "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": l, "item": u + p}
                                for i, (l, p) in enumerate(items)]}


def short_title(R):
    return R.title.removesuffix(" · NK15068")


# --------------------------------------------------------------------------- the page


def script_tags(R):
    from .routes import SCRIPTS
    out = []
    for k in R.scripts:
        src = SCRIPTS[k]
        out.append(f'<script src="{src if src.startswith("http") else rel(R, src)}"></script>')
    return "\n".join(out)


def page_html(D, R, result):
    res = {"body": result} if isinstance(result, str) else dict(result)
    upd = res.get("updated") or data_updated(D, R.dates)
    su = site_url(D)
    canon = su + ("/404.html" if R.path == "/404.html" else R.path)
    robots = {"N": '<meta name="robots" content="noindex">', "NF": '<meta name="robots" content="noindex,follow">'}.get(R.index, "")
    og_title = res.get("og_title") or short_title(R)
    og_img = res.get("og_image") or (su + "/img/og-15068.png" if (D["site"] / "img" / "og-15068.png").exists() else "")
    lds = []
    if R.page == "home":
        lds.append(jsonld_website(D))
    elif R.path != "/404.html":
        lds.append(jsonld_breadcrumbs(D, R, res.get("crumbs")))
    lds += res.get("jsonld") or []
    root = R.root
    desc = f'<meta name="description" content="{esc(R.desc)}">\n' if R.desc else ""
    head = [
        BANNER, "<!doctype html>",
        f'<html lang="en" data-page="{R.page}" data-root="{root}">', "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
        f"<title>{esc(R.title)}</title>",
        desc + f'<link rel="canonical" href="{esc(canon)}">',
    ]
    if robots:
        head.append(robots)
    head += [
        '<meta property="og:type" content="website"><meta property="og:site_name" content="NK15068">',
        f'<meta property="og:title" content="{esc(og_title)}">' +
        (f'<meta property="og:description" content="{esc(R.desc)}">' if R.desc else ""),
        f'<meta property="og:url" content="{esc(canon)}">' +
        (f'<meta property="og:image" content="{esc(og_img)}">' if og_img else ""),
        '<meta name="twitter:card" content="summary_large_image"><meta name="theme-color" content="#8a1c2b">',
        f'<link rel="icon" href="{root}favicon.svg" type="image/svg+xml"><link rel="manifest" href="{root}manifest.webmanifest">',
        THEME_BOOT, FONTS, f'<link rel="stylesheet" href="{root}assets/nk.css">',
    ]
    if R.page == "home":
        head.append(LEGACY)
    if res.get("head"):
        head.append(res["head"])
    if D.get("board") is not None and "pets" in R.scripts:  # pets.js reads data/pets-board.json only when it exists
        head.append(f'<meta name="nk-pets-snapshot" content="{esc(D["board"].get("fetched") or "")}">')
    ha = head_ads(D, R)
    if ha:
        head.append(ha)
    head += [jsonld_tag(o) for o in lds]
    head.append("</head>")
    main = crumbs_html(R, [c for c in (res.get("crumbs") or [])]) + res["body"]
    main = place_ads(D, R, main)
    no_foot = R.page in ("map", "map3d")
    body = [
        "<body>", '<a class="skip" href="#main">Skip to content</a>',
        masthead(D, R, upd), secbar(D, R),
        f'<main id="main"{res.get("main_attrs", "")}>{main}</main>',
        "" if no_foot else footer(D, R, upd),
        script_tags(R), "</body></html>", "",
    ]
    return "\n".join(head + [b for b in body if b])
