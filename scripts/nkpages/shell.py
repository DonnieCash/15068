# --------------------------------------------------------------------------- links


def rel(frm, to):
    """Link from route `frm` to site path `to` ("/lost-pets/", "/", "data/x.json", "#id")."""
    if to.startswith(("#", "http:", "https:", "mailto:", "tel:")):
        return to
    root = frm.root if hasattr(frm, "root") else frm
    t = to.lstrip("/")
    return (root + t) or "./"


def correction_url(D):
    return f"https://github.com/{D['cfg']['repo']}/issues/new?template=correction.yml"


def issues_url(D):
    return f"https://github.com/{D['cfg']['repo']}/issues"


def ads_on(D):
    return bool((D["cfg"].get("adsense_client") or "").strip())


